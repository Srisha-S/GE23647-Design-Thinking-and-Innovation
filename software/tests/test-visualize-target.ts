import assert from 'node:assert/strict';
import { colorInfo } from '../src/lib/color.ts';
import { hasLatestScan, previewMetadata, snapshotTarget } from '../src/features/visualize/visualizeTypes.ts';
import type { ColourRecord } from '../src/types.ts';
import { ManualMaskProvider } from '../src/features/visualize/maskProvider.ts';
import { createMask } from '../src/features/visualize/mask.ts';

let checks = 0;
const check = (condition: unknown, label: string) => { assert.ok(condition, label); checks++; };
const equal = (actual: unknown, expected: unknown, label: string) => { assert.deepEqual(actual, expected, label); checks++; };
const record: ColourRecord = {
  id: 'library-proof', name: 'Captured Rose', hex: '#B4556B', rgb: { r: 180, g: 85, b: 107 }, tags: ['textile'],
  source: 'bluetooth', clear: 630, createdAt: '2026-09-30T08:30:00.000Z', projectId: 'collection-proof',
};
const before = structuredClone(record);
const scan = snapshotTarget(record, 'Latest Scan');
equal(scan.colourSource, 'Latest Scan', 'A latest scan retains the explicit colour source.');
equal(scan.colour, before, 'A scan snapshot retains all existing CHROMA colour fields.');
check(!scan.libraryItemId && !scan.libraryItemName, 'A scan is not falsely marked as a Library item.');
const library = snapshotTarget(record, 'Library');
equal(library.libraryItemId, record.id, 'A Library snapshot records original identity.');
equal(library.libraryItemName, record.name, 'A Library snapshot records the stored name.');
equal(library.colour, record, 'Target creation preserves source, clear, project and tags.');
record.rgb.r = 0; record.tags.push('changed'); record.name = 'Edited later';
equal(library.colour.rgb.r, 180, 'Later record mutations cannot change selected target RGB.');
equal(library.colour.tags, ['textile'], 'Selected tags are independently snapshotted.');
equal(library.libraryItemName, 'Captured Rose', 'Later renaming does not silently alter the selected snapshot.');
equal(scan.colour.name, 'Captured Rose', 'Later readings do not replace a selected scan.');
const next = snapshotTarget({ ...before, id: 'next-colour', hex: '#2387F5' }, 'Library');
equal(next.colour.hex, '#2387F5', 'Changing target selects the new HEX.');
equal(next.colour.rgb, colorInfo('#2387F5').rgb, 'Shared conversions provide the new target RGB.');
equal(library.colour.hex, '#B4556B', 'Changing target leaves the previous and Library snapshots intact.');
for (const source of ['bluetooth', 'usb', 'wifi', 'demo']) check(hasLatestScan({ ...before, source }), `${source} captures can be selected.`);
for (const source of ['sample', 'manual', 'convert']) check(!hasLatestScan({ ...before, source }), `${source} is not falsely labelled as a CHROMAPOD scan.`);
const dimensions = { width: 3200, height: 1800 };
const photo = { name: 'curtains.png', naturalWidth: 3200, naturalHeight: 1800 };
const metadata = previewMetadata(library, photo, 50, dimensions);
equal(metadata.targetRgb, colorInfo(before.hex).rgb, 'Exported RGB uses the existing conversion system.');
equal(metadata.targetLab, colorInfo(before.hex).lab, 'Exported LAB uses the existing conversion system.');
equal(metadata.libraryItemId, before.id, 'Image metadata retains the Library item ID.');
equal(metadata.libraryItemName, before.name, 'Image metadata retains the selected Library name.');
equal(metadata.readingSource, 'bluetooth', 'Library selection does not overwrite the original reading source.');
equal(metadata.capturedAt, before.createdAt, 'Metadata retains the original capture date.');
equal(metadata.intensity, 50, 'Metadata retains the requested intensity.');
equal(metadata.intensityUnit, 'percent', 'Exported intensity has an unambiguous unit.');
equal([metadata.outputWidth, metadata.outputHeight], [3200, 1800], 'Metadata records output dimensions independently of display size.');
equal([metadata.naturalWidth, metadata.naturalHeight], [3200, 1800], 'Metadata retains original image dimensions.');
equal(metadata.imageName, photo.name, 'Metadata identifies the local source photo.');
const demo = previewMetadata(snapshotTarget({ ...before, source: 'demo' }, 'Latest Scan'), photo, 100, dimensions);
equal(demo.readingSource, 'demo', 'A simulated reading remains explicitly simulated in exported metadata.');
check(!('libraryItemId' in demo), 'Scan export does not invent Library metadata.');
check(Number.isFinite(Date.parse(demo.createdAt)), 'Export timestamp is valid.');
const material = previewMetadata(library, photo, 85, dimensions, { material: 'wood', lighting: 'warm', selectionMethod: 'sam3', selectionRefined: true });
equal(material.material, 'wood', 'Export retains the selected material profile.');
equal(material.materialLabel, 'Wood', 'Export names the material.');
equal(material.lighting, 'warm', 'Export retains the LightShift preset.');
equal(material.lightingKelvin, 2700, 'Export records the indicative colour temperature.');
equal(material.lightShiftModel, 'lab-cast-approximation', 'Export describes lighting as an approximation.');
equal(material.selectionMethod, 'sam3', 'Export records the actual selection method.');
equal(material.selectionRefined, true, 'Export records manual refinement.');
equal(material.renderer, 'lab-material-v2', 'Export identifies the material renderer.');
equal(material.targetLab, metadata.targetLab, 'Lighting cannot change the canonical scanned target LAB.');
equal(material.libraryItemId, metadata.libraryItemId, 'Appearance settings preserve Library identity.');
check(!('material' in metadata), 'Legacy callers keep the existing metadata shape.');
const provider = new ManualMaskProvider(5, 1);
const sam = createMask(5, 1); sam.data[0] = 255;
provider.applySelection(sam, 'replace', 'sam3');
provider.stroke({ x: 2.5, y: .5 }, { x: 2.5, y: .5 }, .4, 'brush'); provider.endStroke(); provider.undo();
const local = createMask(5, 1); local.data[3] = 255;
provider.applySelection(local, 'replace', 'local-region'); provider.undo();
const restored = previewMetadata(library, photo, 100, dimensions, { material: 'paint', lighting: 'daylight', ...provider.provenance });
equal(restored.selectionMethod, 'sam3', 'PNG metadata after Brush Undo and Local Undo identifies the restored SAM mask.');
equal(restored.selectionRefined, false, 'PNG metadata after both Undo paths restores the original unrefined state.');
equal(provider.mask, sam, 'Export provenance and exact restored SAM bytes describe the same mask.');
equal(restored.libraryItemId, before.id, 'Restoring selection provenance preserves the existing Library identity.');
console.log(`Visualize colour sources: ${checks} checks passed.`);
