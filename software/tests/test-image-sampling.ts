import assert from 'node:assert/strict';
import { averageImagePixels, displayToImagePixel, imageSampleBounds } from '../src/lib/imageSampling.ts';
import { colorInfo, rgbToHex } from '../src/lib/color.ts';

let checks = 0;
function equal(actual: unknown, expected: unknown, message: string) { assert.deepEqual(actual, expected, message); checks++; }
const natural = { width: 4000, height: 2000 };
const css = { left: 10, top: 20, width: 400, height: 200 };
equal(displayToImagePixel({ x: 210, y: 120 }, css, natural), { x: 2000, y: 1000 }, 'Responsive CSS coordinates map to original pixels, independent of DPR.');
equal(displayToImagePixel({ x: 10, y: 20 }, css, natural), { x: 0, y: 0 }, 'Top-left pixel.');
equal(displayToImagePixel({ x: 410, y: 220 }, css, natural), { x: 3999, y: 1999 }, 'Exact bottom-right border clamps to the last pixel.');
equal(displayToImagePixel({ x: 411, y: 220 }, css, natural), null, 'Outside taps are ignored.');
const letterbox = { left: 20, top: 30, width: 400, height: 400 };
equal(displayToImagePixel({ x: 220, y: 80 }, letterbox, natural), null, 'Top contain letterbox is not an image pixel.');
equal(displayToImagePixel({ x: 220, y: 380 }, letterbox, natural), null, 'Bottom contain letterbox is ignored.');
equal(displayToImagePixel({ x: 220, y: 230 }, letterbox, natural), { x: 2000, y: 1000 }, 'Contain-centred image mapping.');
equal(displayToImagePixel({ x: 70, y: 230 }, letterbox, { width: 2000, height: 4000 }), null, 'Side contain letterbox is ignored.');
equal(displayToImagePixel({ x: 120, y: 30 }, letterbox, { width: 2000, height: 4000 }), { x: 0, y: 0 }, 'Portrait image content origin.');
equal(displayToImagePixel({ x: 0, y: 0 }, { ...css, width: 0 }, natural), null, 'Zero display bounds are safe while hidden.');
equal(displayToImagePixel({ x: NaN, y: 0 }, css, natural), null, 'Invalid client coordinates are safe.');
equal(displayToImagePixel({ x: 0, y: 0 }, css, { width: 0, height: 0 }), null, 'Missing image dimensions are safe.');
equal(displayToImagePixel({ x: 0, y: 0 }, css, { width: 10.5, height: 4 }), null, 'Malformed image dimensions are safe.');
equal(imageSampleBounds({ x: 50, y: 60 }, natural), { x: 49, y: 59, width: 3, height: 3 }, 'Interior neighbourhood uses exactly 3 × 3 original pixels.');
equal(imageSampleBounds({ x: 0, y: 0 }, natural), { x: 0, y: 0, width: 2, height: 2 }, 'Top-left sampling is clipped without repeating pixels.');
equal(imageSampleBounds({ x: 3999, y: 1999 }, natural), { x: 3998, y: 1998, width: 2, height: 2 }, 'Bottom-right sampling is clipped.');
equal(imageSampleBounds({ x: 0, y: 0 }, { width: 1, height: 1 }), { x: 0, y: 0, width: 1, height: 1 }, 'Single pixel images work.');
equal(imageSampleBounds({ x: 1, y: 0 }, { width: 3, height: 1 }), { x: 0, y: 0, width: 3, height: 1 }, 'One-dimensional images work.');
equal(imageSampleBounds({ x: -1, y: 0 }, natural), null, 'Negative pixels are rejected.');
equal(imageSampleBounds({ x: 4000, y: 0 }, natural), null, 'Out-of-range pixels are rejected.');
equal(imageSampleBounds({ x: .2, y: 0 }, natural), null, 'Noninteger coordinates are rejected.');
equal(imageSampleBounds({ x: 0, y: 0 }, { width: 0, height: 2 }), null, 'Missing sampling image is rejected.');
const rgba = new Uint8ClampedArray(Array.from({ length: 9 }, () => [224, 53, 77, 255]).flat());
const rgb = averageImagePixels(rgba)!;
equal(rgb, { r: 224, g: 53, b: 77 }, 'Solid neighbourhood preserves target RGB.');
const info = colorInfo(rgbToHex(rgb.r, rgb.g, rgb.b));
equal(info.hex, '#E0354D', 'Shared conversion generates target HEX.');
equal(Object.values(info.lab).every(Number.isFinite), true, 'Shared conversion generates finite target LAB.');
equal(averageImagePixels([255, 0, 0, 255, 0, 0, 255, 255]), { r: 128, g: 0, b: 128 }, 'Averaging is deterministic and rounds once at the end.');
equal(averageImagePixels([0, 255, 0, 0]), { r: 255, g: 255, b: 255 }, 'Invisible pixels composite to white.');
equal(averageImagePixels([255, 0, 0, 128]), { r: 255, g: 127, b: 127 }, 'Partial alpha composites onto white.');
equal(averageImagePixels([0, 0, 0, 255, 255, 0, 0, 0]), { r: 128, g: 128, b: 128 }, 'Every visible background pixel contributes consistently.');
equal(averageImagePixels([]), null, 'Empty RGBA data is rejected safely.');
equal(averageImagePixels([255, 0, 0]), null, 'Truncated RGBA data is rejected safely.');
equal(averageImagePixels([NaN, 0, 0, 255]), null, 'Nonfinite RGBA data is rejected safely.');
equal(averageImagePixels([256, 0, 0, 255]), null, 'Invalid RGBA data is rejected safely.');
console.log(`${checks} image sampling checks passed.`);
